-- ==========================================
-- BANCO DE DADOS: BIBLIOTECA
-- TABELAS E RELACIONAMENTOS
-- ==========================================


-- ==========================================
-- 1. TABELA DE USUÁRIOS
-- ==========================================

CREATE TABLE IF NOT EXISTS public.usuario (
    id_usuario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,
    data_cadastro TIMESTAMPTZ NOT NULL DEFAULT NOW()
);


-- ==========================================
-- 2. TABELA DE LIVROS
-- ==========================================

CREATE TABLE IF NOT EXISTS public.livro (
    id_livro BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo VARCHAR(200) NOT NULL,
    autor VARCHAR(150) NOT NULL,
    isbn VARCHAR(20) UNIQUE,
    quantidade_disponivel INTEGER NOT NULL DEFAULT 0,

    CONSTRAINT chk_livro_quantidade
        CHECK (quantidade_disponivel >= 0)
);


-- ==========================================
-- 3. TABELA DE EMPRÉSTIMOS
-- ==========================================

CREATE TABLE IF NOT EXISTS public.emprestimo (
    id_emprestimo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario BIGINT NOT NULL,
    data_emprestimo TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    data_devolucao_prevista TIMESTAMPTZ NOT NULL,

    CONSTRAINT fk_emprestimo_usuario
        FOREIGN KEY (id_usuario)
        REFERENCES public.usuario(id_usuario),

    CONSTRAINT chk_data_devolucao
        CHECK (data_devolucao_prevista >= data_emprestimo)
);


-- ==========================================
-- 4. TABELA DE ITENS DO EMPRÉSTIMO
-- ==========================================

CREATE TABLE IF NOT EXISTS public.item_emprestimo (
    id_emprestimo BIGINT NOT NULL,
    id_livro BIGINT NOT NULL,

    PRIMARY KEY (id_emprestimo, id_livro),

    CONSTRAINT fk_item_emprestimo
        FOREIGN KEY (id_emprestimo)
        REFERENCES public.emprestimo(id_emprestimo),

    CONSTRAINT fk_item_livro
        FOREIGN KEY (id_livro)
        REFERENCES public.livro(id_livro)
);


-- ==========================================
-- 5. ÍNDICES PARA CONSULTAS
-- ==========================================

CREATE INDEX IF NOT EXISTS idx_emprestimo_usuario
    ON public.emprestimo(id_usuario);

CREATE INDEX IF NOT EXISTS idx_item_emprestimo_livro
    ON public.item_emprestimo(id_livro);

CREATE INDEX IF NOT EXISTS idx_emprestimo_data
    ON public.emprestimo(data_emprestimo);


